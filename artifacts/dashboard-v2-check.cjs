const { chromium } = require('../apps/web/node_modules/playwright');
const path = require('path');
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  const requests = [];
  page.on('request', r => { if (r.url().includes('/api/v1/')) requests.push(r.url()); });
  await page.goto('http://127.0.0.1:3000', { waitUntil: 'networkidle' });
  await page.getByRole('button', { name: 'Explore the demo', exact: true }).click();
  await page.getByRole('heading', { name: 'Your money, in focus.' }).waitFor();
  await page.locator('.dashboard-metric').first().waitFor();
  await page.screenshot({ path: path.join(__dirname, 'dashboard-v2-desktop.png'), fullPage: true });
  if (requests.some(r => r.includes('/dashboard/summary'))) throw Error('Sample dashboard made an unnecessary API request');
  await page.getByRole('textbox', { name: 'Search dashboard subscriptions' }).fill('Spotify');
  if (await page.locator('.dashboard-table tbody tr').count() !== 1) throw Error('Dashboard search failed');
  await page.getByRole('textbox', { name: 'Search dashboard subscriptions' }).clear();
  await page.getByRole('link', { name: 'Explore relationships', exact: true }).click();
  await page.getByRole('heading', { name: 'Connect the dots.' }).waitFor();
  await page.getByRole('button', { name: 'Commitment: Spotify Premium', exact: true }).click();
  await page.locator('.relation-inspector h3').getByText('Spotify Premium').waitFor();
  const overviewCount = await page.locator('.graph-node-button').count();
  await page.getByRole('button', { name: 'Evidence', exact: true }).click();
  const evidenceCount = await page.locator('.graph-node-button').count();
  if (evidenceCount <= overviewCount) throw Error('Transaction evidence was not expanded');
  await page.getByRole('button', { name: 'Overview', exact: true }).click();
  await page.getByRole('combobox', { name: 'Filter graph by category' }).selectOption('Storage');
  if (await page.locator('.graph-node-button').count() >= overviewCount) throw Error('Graph category filter failed');
  await page.getByRole('combobox', { name: 'Filter graph by category' }).selectOption('All categories');
  await page.getByRole('button', { name: 'Zoom in', exact: true }).click();
  await page.getByRole('button', { name: 'Reset graph zoom' }).getByText('115%').waitFor();
  await page.getByRole('button', { name: 'Reset graph zoom' }).click();
  await page.screenshot({ path: path.join(__dirname, 'relationships-v2-desktop.png'), fullPage: true });
  console.log('Graph overview/evidence nodes:', overviewCount, evidenceCount);
  await page.getByRole('button', { name: 'Connected', exact: true }).click();
  await page.locator('.relation-heading .source-relational, .relation-heading .source-neo4j').waitFor({ timeout: 20000 });
  console.log('Connected graph source:', await page.locator('.relation-heading .data-source').innerText());
  await page.getByRole('link', { name: 'Overview', exact: true }).click();
  await page.locator('.dashboard-metrics').waitFor({ timeout: 15000 });
  if ((await page.locator('.dashboard-metric').nth(0).innerText()).includes('Across 8 active')) throw Error('Connected dashboard still showed sample data');
  const start = Date.now();
  await page.getByRole('link', { name: 'Relationships', exact: true }).click();
  await page.getByRole('link', { name: 'Overview', exact: true }).click();
  await page.locator('.dashboard-metrics').waitFor();
  console.log('Client cached navigation ms:', Date.now() - start);
  await page.screenshot({ path: path.join(__dirname, 'dashboard-v2-connected.png'), fullPage: true });
  await page.getByRole('button', { name: 'Sample', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: path.join(__dirname, 'dashboard-v2-mobile.png'), fullPage: true });
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  if (overflow) throw Error('Mobile dashboard overflows');
  await page.getByRole('link', { name: 'Explore relationships', exact: true }).click();
  await page.getByRole('button', { name: 'Commitment: Spotify Premium', exact: true }).evaluate(node => {
    const viewport = node.closest('.relation-canvas');
    const r = node.getBoundingClientRect(), v = viewport.getBoundingClientRect();
    viewport.scrollLeft += r.left - v.left - 50;
    viewport.scrollTop += r.top - v.top - 120;
  });
  await page.getByRole('button', { name: 'Commitment: Spotify Premium', exact: true }).click();
  console.log('Mobile inspector state:', await page.locator('.relation-inspector').evaluate(el => ({ text: el.textContent, display: getComputedStyle(el).display, selected: document.querySelectorAll('.graph-node-button.is-selected').length })));
  await page.screenshot({ path: path.join(__dirname, 'relationships-v2-mobile.png'), fullPage: true });
  await page.locator('.relation-inspector h3').getByText('Spotify Premium').waitFor({ timeout: 5000 });
  await page.screenshot({ path: path.join(__dirname, 'relationships-v2-mobile.png'), fullPage: true });
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw Error('Mobile graph overflows');
  if (errors.length) throw Error('Browser errors: ' + JSON.stringify(errors));
  console.log('Dashboard, live API, graph controls, mobile layouts and browser checks passed.');
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
