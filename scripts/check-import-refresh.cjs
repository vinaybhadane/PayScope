const assert = require('node:assert/strict');
const { chromium } = require('../apps/web/node_modules/playwright');
const path = require('node:path');
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  page.setDefaultTimeout(120000);
  await page.addInitScript(() => sessionStorage.setItem('payscope_intro_transition_seen', 'true'));
  await page.goto('http://127.0.0.1:3000');
  await page.getByRole('button', { name: 'Explore the demo', exact: true }).click();
  await page.locator('.dashboard-metric').first().waitFor();
  await page.goto('http://127.0.0.1:3000/upload');
  await page.getByRole('checkbox').first().check();
  await page.locator('input[type=file]').setInputFiles(path.join(__dirname, '../sample_data/synthetic_bank_statement.csv'));
  await page.getByRole('button', { name: 'Confirm & Import to Workspace' }).waitFor();
  const saved = page.waitForResponse(r => r.url().endsWith('/api/v1/imports') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Confirm & Import to Workspace' }).click();
  const response = await saved;
  const result = await response.json();
  assert.equal(response.status(), 201);
  assert.equal(result.workspace_refresh.analysis_status, 'completed', JSON.stringify(result.workspace_refresh));
  assert.equal(result.workspace_refresh.graph_status, 'completed', JSON.stringify(result.workspace_refresh));
  await page.getByRole('link', { name: 'View updated dashboard' }).click();
  await page.locator('.dashboard-metric').first().waitFor();
  assert.equal(await page.getByRole('button', { name: 'Connected', exact: true }).getAttribute('aria-pressed'), 'true');
  assert.equal(await page.locator('.data-source').innerText(), 'Live workspace');
  await page.goto('http://127.0.0.1:3000/relationships');
  await page.getByText('Neo4j connected', { exact: true }).waitFor();
  console.log('PASS real file import → PostgreSQL analysis → connected dashboard → live Neo4j graph', result.workspace_refresh);
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
